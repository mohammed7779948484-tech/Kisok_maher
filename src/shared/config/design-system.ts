function toKebabCase(value: string): string {
  return value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)
}

export function createDesignTokenVariables(): Record<string, string> {
  const { colors, typography, spacing, radii, elevations, sizing, breakpoints, motion } = designSystem

  return {
    '--font-sans': 'var(--font-inter)',
    ...Object.fromEntries(Object.entries(colors).map(([key, value]) => [`--color-${toKebabCase(key)}`, value])),
    ...Object.fromEntries(Object.entries(typography).flatMap(([key, [size, lineHeight, weight]]) => [
      [`--type-${toKebabCase(key)}-size`, size],
      [`--type-${toKebabCase(key)}-line`, lineHeight],
      [`--type-${toKebabCase(key)}-weight`, weight],
    ])),
    ...Object.fromEntries(Object.entries(spacing).map(([key, value]) => [`--space-${key}`, value])),
    ...Object.fromEntries(Object.entries(radii).map(([key, value]) => [`--radius-${toKebabCase(key)}`, value])),
    ...Object.fromEntries(Object.entries(elevations).map(([key, value]) => [`--elevation-${key}`, value])),
    ...Object.fromEntries(Object.entries(sizing).map(([key, value]) => [`--size-${toKebabCase(key)}`, value])),
    ...Object.fromEntries(Object.entries(breakpoints).map(([key, value]) => [`--breakpoint-${toKebabCase(key)}`, value])),
    ...Object.fromEntries(Object.entries(motion).map(([key, value]) => [`--motion-${toKebabCase(key)}`, value])),
  }
}

export type DesignSystem = typeof designSystem
